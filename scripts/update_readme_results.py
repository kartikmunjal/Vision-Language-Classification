#!/usr/bin/env python3
"""Refresh the README headline metrics from committed result JSON."""
from __future__ import annotations
import argparse,json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1];README=ROOT/"README.md"
START="<!-- GENERATED_RESULTS_START -->";END="<!-- GENERATED_RESULTS_END -->"
load=lambda p:json.loads((ROOT/p).read_text())
pct=lambda x:f"{100*x:.2f}%";interval=lambda x:f"[{pct(x[0])}, {pct(x[1])}]"

def generated():
    stage3=load("results/stage3_powered_followup.json")["result"]
    silver=load("results/annotation_free_evaluation.json")["tasks"]
    seq2=load("results/research_sequence/sequence2_reward_model.json")["result"]
    seq3=load("results/research_sequence/sequence3_results.json")["result"]
    seq4=load("results/research_sequence/sequence4_results.json")["result"]["budgets"]["0.2"]
    seq5=load("results/research_sequence/sequence5_results.json")["result"]["paired_deltas_hard_minus_random"]["text_to_image"]["recall_at_1"]
    seq6=load("results/research_sequence/sequence6_results.json")["result"]
    natural=load("results/followup/natural_video.json")
    verified=load("results/followup/verified_negative_retrieval.json")["result"]["paired_deltas_verified_mixed_minus_random"]["text_to_image"]["recall_at_1"]
    active=load("results/followup/active_acquisition.json")["result"]["budgets"]
    sugar=load("results/followup/sugarcrepe.json")["result"]
    lines=[START,"## Headline results","","This section is regenerated by `scripts/update_readme_results.py` from committed JSON artifacts.","",
    "| Experiment | Result | Evidence |","|---|---|---|"]
    for task in ["animal_present","human_present","multiple_subjects"]:
        m=silver[task]["weak_sources"]["ensemble"]["accuracy"]
        lines.append(f"| Ensemble silver-label accuracy: `{task}` | {pct(m['estimate'])}, 95% CI {interval(m['ci95'])} | n={m['n']}, N_trials={m['n_trials']} |")
    lines += [
      f"| Powered Stage 3 quality-slice disagreement | {pct(stage3['estimate'])}, 95% CI {interval(stage3['ci95'])}; hypothesis not supported | flagged n={stage3['n_flagged']}, comparison n={stage3['n_comparison']}, N_trials={stage3['n_trials']} |",
      f"| Learned preference reward accuracy | {pct(seq2['learned']['accuracy'])} vs {pct(seq2['handcrafted']['accuracy'])}; delta {pct(seq2['paired_deltas_learned_minus_handcrafted']['accuracy']['estimate'])}, 95% CI {interval(seq2['paired_deltas_learned_minus_handcrafted']['accuracy']['ci95'])} | n={seq2['n_pairs']}, N_trials={seq2['n_trials']} |",
      f"| Controlled temporal retrieval: occlusion | Recall@1 {pct(seq3['occlusion']['frames'][-1]['recall_at_1'])}, down {pct(seq3['occlusion']['rank1_retention_frame0_minus_frame7'])} from frame 0 | n={seq3['occlusion']['n_sequences']}, N_trials=1 |",
    ]
    for task in ["human_present","animal_present","multiple_subjects"]:
        m=seq4[task]["metrics"]["accuracy"]
        lines.append(f"| Targeted correction retraining at 20%: `{task}` | targeted − random {pct(m['estimate'])}, 95% CI {interval(m['ci95'])} | N_trials={m['n_trials']} |")
    lines += [
      f"| Hard-only negative mining, text→image Recall@1 | hard − random {pct(seq5['estimate'])}, 95% CI {interval(seq5['ci95'])} | N_trials=5 |",
      f"| Caption-negation robustness | Negated caption preferred on {pct(seq6['caption_attacks']['negation_preferred_over_original_rate'])} | n={seq6['caption_attacks']['n']}, N_trials=1 |",
      f"| UCF101 frozen CLIP clean / blurred top-1 | {pct(natural['zero_shot']['clean']['accuracy'])} / {pct(natural['zero_shot']['blur']['accuracy'])} | decoded n={natural['n_decoded']}, N_trials=1 |",
      f"| UCF101 temporal adapter under blur | temporal − mean {pct(natural['paired_deltas_temporal_minus_mean']['blur']['estimate'])}, 95% CI {interval(natural['paired_deltas_temporal_minus_mean']['blur']['ci95'])} | N_trials=5 |",
      f"| Object-verified mixed negatives, text→image Recall@1 | mixed − random {pct(verified['estimate'])}, 95% CI {interval(verified['ci95'])} | N_trials={verified['n_trials']} |",
      f"| Multi-objective acquisition at 10% / 20% | composite − disagreement {pct(active['0.1']['macro_accuracy']['composite_minus_disagreement']['estimate'])} / {pct(active['0.2']['macro_accuracy']['composite_minus_disagreement']['estimate'])} | N_trials=5 |",
      f"| SugarCrepe add / replace / swap | {pct(sugar['add']['accuracy'])} / {pct(sugar['replace']['accuracy'])} / {pct(sugar['swap']['accuracy'])} | n={sugar['add']['n']} / {sugar['replace']['n']} / {sugar['swap']['n']}, N_trials=1 |",
      "","Detailed slice metrics, calibration results, predictions, and provenance remain in the generated reports linked below.",END]
    return "\n".join(lines)

def main():
    ap=argparse.ArgumentParser();ap.add_argument("--check",action="store_true");a=ap.parse_args();text=README.read_text()
    if START not in text or END not in text:raise SystemExit("README generated-result markers are missing")
    before=text.split(START,1)[0];after=text.split(END,1)[1];updated=before+generated()+after
    if a.check:
        if updated!=text:raise SystemExit("README headline results are stale; run scripts/update_readme_results.py")
    else:README.write_text(updated)
if __name__=="__main__":main()
